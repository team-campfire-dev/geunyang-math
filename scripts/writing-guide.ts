/**
 * Copies the 「지침」 section of docs/lesson-writing-guide.md into the module the problem writer reads.
 *
 *   npm run guide:sync
 *
 * The document is where the guidelines are written and argued over; the server cannot read docs/ in
 * a deployment, so it reads this copy. A test fails while the two differ, which is the reminder to
 * run this after editing the guide.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { guidelinesOf } from '../src/server/writing-guide-source';

const target = 'src/server/writing-guide.ts';
const lines = guidelinesOf(readFileSync('docs/lesson-writing-guide.md', 'utf8')).split('\n');
writeFileSync(target, [
  '// Generated by `npm run guide:sync` from docs/lesson-writing-guide.md (「지침」). Edit the document, not this file.',
  'export const writingGuide = [',
  ...lines.map((line) => `  ${JSON.stringify(line)},`),
  "].join('\\n');",
  '',
].join('\n'));
console.log(`${target}: ${lines.length} lines.`);
